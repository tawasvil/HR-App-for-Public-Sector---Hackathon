export function buildDashboardPayload(
  employees: Employee[],
  alarms: AlarmTrigger[],
  contractOutlook: MonthlyContractOutlook[],
  zeroClickPolicyEnabled = true
): DashboardPayload {
  const activeAlarms = alarms.filter((a) => !a.resolved);
  const categoryCoverage = computeCategoryCoverage(employees);

  // Unit-wide 42 personnel (34 permanent, 8 fixed-term): baseline 37 compliant + dynamic updates as alarms resolve
  const resolvedCount = alarms.filter((a) => a.resolved).length;
  const complianceRatePct = Math.min(99, 88 + resolvedCount * 2);

  return {
    unitName: UNIT_METADATA.unitName,
    organizationName: UNIT_METADATA.organizationName,
    zeroClickPolicyEnabled,
    supervisor: SUPERVISOR_INFO,
    overview: {
      totalPersonnel: 42,
      permanentCount: 34,
      fixedTermCount: 8,
      complianceRatePct,
      urgentActionsCount: activeAlarms.length,
      rosterSampleCount: employees.length,
    },
    alarms,
    employees,
    categoryCoverage,
    contractOutlook,
  };
}
