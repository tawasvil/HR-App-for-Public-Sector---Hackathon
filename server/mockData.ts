export function computeCategoryCoverage(employees: Employee[]): CategoryCoverage[] {
  const categories: CategoryCoverage['category'][] = [
    'Safety Permits',
    'Information Security',
    'Role Certifications',
    'Leadership Training',
  ];

  // Baseline unit scale factors combined with live 10-profile status so every resolved action moves real percentages
  const baselineBonus: Record<CategoryCoverage['category'], { total: number; compliant: number }> = {
    'Safety Permits': { total: 32, compliant: 30 },
    'Information Security': { total: 32, compliant: 27 },
    'Role Certifications': { total: 32, compliant: 30 },
    'Leadership Training': { total: 14, compliant: 11 },
  };

  return categories.map((category) => {
    let sampleTotal = 0;
    let sampleCompliant = 0;

    for (const emp of employees) {
      const catPermits = emp.permits.filter((p) => p.category === category);
      const catTrainings = emp.trainings.filter((t) => t.category === category && t.mandatory);

      for (const p of catPermits) {
        sampleTotal += 1;
        if (p.status === 'Valid') sampleCompliant += 1;
      }
      for (const t of catTrainings) {
        sampleTotal += 1;
        if (t.status === 'Completed' || t.status === 'Scheduled') sampleCompliant += 1;
      }
    }

    const totalCount = baselineBonus[category].total + sampleTotal;
    const compliantCount = baselineBonus[category].compliant + sampleCompliant;
    const percentage = totalCount > 0 ? Math.round((compliantCount / totalCount) * 100) : 100;

    return {
      category,
      compliantCount,
      totalCount,
      percentage,
    };
  });
}

